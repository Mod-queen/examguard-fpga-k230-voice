`timescale 1ns/1ps
module maintenance_endpoint_tb;
    reg clk=0,rst=1;always #10 clk=~clk;
    reg rx_valid=0;reg [7:0] rx_data=0;
    reg [31:0] device_id=1,boot_id=18,generation=18;reg boot_done=1,config_known=1;
    reg [255:0] active_config=0;
    wire request_valid,result_ready,byte_valid,byte_last,command_pending;
    reg request_ready=1,result_valid=0,byte_ready=0;
    wire [1:0] opcode;wire [255:0] proposed_config;wire [55:0] calendar_data;
    reg [1:0] result_opcode=0,result_recovery_error=0;
    reg [3:0] result_error=0,result_detail=0,result_store_error=0;
    reg result_write_attempted=0;reg [71:0] result_snapshot=0;
    wire [7:0] byte_data;wire [31:0] rejected_lines;
    maintenance_endpoint dut(.*);
    reg [511:0] commands[0:5];integer requests=0,records=0,bytes_seen=0,trace;
    reg [31:0] rng=32'h6abc1983;reg [7:0] held_byte;reg old_stall=0;
    reg [1:0] captured_opcode;
    always @(negedge clk) if(!rst) begin
        rng={rng[30:0],rng[31]^rng[21]^rng[1]^rng[0]};byte_ready=rng[0] || rng[1];
    end
    always @(posedge clk) if(!rst) begin
        if(old_stall && (!byte_valid || byte_data!==held_byte)) $fatal(1,"FAIL: MR byte changed under stall");
        old_stall<=byte_valid && !byte_ready;held_byte<=byte_data;
        if(request_valid && request_ready) begin
            requests=requests+1;captured_opcode=opcode;
            if(opcode==1 && proposed_config!=={120'd0,8'h01,16'sd480,16'd600,32'd42,64'h0000200131504745})
                $fatal(1,"FAIL: profile endian");
            if(opcode==2 && calendar_data!==56'h26100321123456) $fatal(1,"FAIL: calendar endian");
        end
        if(byte_valid && byte_ready) begin
            $fdisplay(trace,"%02x",byte_data);bytes_seen=bytes_seen+1;
            if(byte_last) begin
                if(bytes_seen!=196) $fatal(1,"FAIL: MR record shape");
                records=records+1;bytes_seen=0;
            end
        end
    end else old_stall<=0;
    task automatic send_byte(input [7:0] b);
        begin @(negedge clk);rx_valid=1;rx_data=b;@(negedge clk);rx_valid=0;end
    endtask
    task automatic send(input [511:0] data);
        reg [3:0] nibble;integer k;
        begin
            send_byte("M");send_byte("C");send_byte(",");
            for(k=0;k<128;k=k+1) begin
                nibble=data[511-4*k -: 4];send_byte(nibble<10?"0"+nibble:"A"+nibble-10);
            end
            send_byte(10);
        end
    endtask
    task automatic reply;
        begin
            wait(dut.state==2);repeat(5) @(negedge clk);
            result_opcode=captured_opcode;result_valid=1;
            @(posedge clk);while(!result_ready) @(posedge clk);
            @(negedge clk);result_valid=0;
        end
    endtask
    task automatic wait_records(input integer count);
        begin wait(records==count);repeat(3) @(negedge clk);end
    endtask
    initial begin
        trace=$fopen("maintenance_results.hex","w");
        $readmemh("D:/fpga_race/docs/baselines/maintenance_commands_20261021.mem",commands);
        repeat(5) @(negedge clk);rst=0;
        send(commands[0]);reply();wait_records(1);
        // Identical most recent request replays old result, no second operation.
        send(commands[0]);wait_records(2);if(requests!=1) $fatal(1,"FAIL: duplicate executed twice");
        send(commands[1]);wait(dut.state==2);active_config=proposed_config;generation=19;result_write_attempted=1;
        reply();wait_records(3);
        send(commands[2]);result_snapshot={56'h26100321123456,16'd0};reply();wait_records(4);
        send(commands[3]);wait_records(5); // wrong boot
        send(commands[4]);wait_records(6); // older token (11), not last token12
        send(commands[5]);wait_records(7); // old token9
        send(commands[2]^512'd1);repeat(200) @(negedge clk); // corrupt CRC drops
        if(requests!=3 || records!=7 || rejected_lines!=1) $fatal(1,"FAIL: command CRC/token gates");
        // Last-token collision gets error7 without reexecuting.
        // Same token12 but valid different operation/body, CRC generated by TB.
        begin: collision
            reg [511:0] altered;reg [31:0] c;integer k;
            altered=commands[0];altered[447:416]=12;c=32'hffffffff;
            for(k=0;k<60;k=k+1) c=dut.receiver.crc_byte(c,altered[511-8*k -: 8]);
            altered[31:0]=~c;send(altered);wait_records(8);
        end
        if(requests!=3) $fatal(1,"FAIL: collision executed");
        begin: mismatched_reply
            reg [511:0] next_command;reg [31:0] c;integer k;
            next_command=commands[0];next_command[447:416]=13;c=32'hffffffff;
            for(k=0;k<60;k=k+1) c=dut.receiver.crc_byte(c,next_command[511-8*k -: 8]);
            next_command[31:0]=~c;send(next_command);wait(dut.state==2);
            @(negedge clk);result_opcode=2;result_valid=1;
            @(negedge clk);result_valid=0;wait_records(9);
        end
        if(requests!=4) $fatal(1,"FAIL: expected one new execution for mismatch test");
        $fclose(trace);
        $display("PASS: maintenance_endpoint requests=%0d records=%0d CRC/endian/duplicate/collision/old-token/boot-binding/backpressure",requests,records);$finish;
    end
    initial begin #5000000;$fatal(1,"FAIL: endpoint timeout state=%0d",dut.state);end
endmodule
